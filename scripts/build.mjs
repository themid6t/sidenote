// Packs the web UI + pdf.js into src/assets.gen.mjs, then (with --compile) builds standalone binaries.
//   node scripts/build.mjs            assets only (enough for `node bin/sidenote.mjs` in development)
//   node scripts/build.mjs --compile  + dist/sidenote-<os>-<arch> for every target (needs bun)
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const nm = (...p) => path.join(ROOT, 'node_modules', ...p);
const assets = {};
function add(urlPath, file) {
  if (fs.statSync(file).isDirectory()) {
    for (const f of fs.readdirSync(file)) add(`${urlPath}/${f}`, path.join(file, f));
  } else if (!file.endsWith('.map') && !file.endsWith('.d.ts')) {
    assets[urlPath] = fs.readFileSync(file).toString('base64');
  }
}
add('/app', path.join(ROOT, 'web'));
add('/vendor/pdfjs/build/pdf.mjs', nm('pdfjs-dist', 'build', 'pdf.min.mjs'));
add('/vendor/pdfjs/build/pdf.worker.mjs', nm('pdfjs-dist', 'build', 'pdf.worker.min.mjs'));
add('/vendor/pdfjs/web/pdf_viewer.mjs', nm('pdfjs-dist', 'web', 'pdf_viewer.mjs'));
add('/vendor/pdfjs/web/pdf_viewer.css', nm('pdfjs-dist', 'web', 'pdf_viewer.css'));
add('/vendor/pdfjs/web/images', nm('pdfjs-dist', 'web', 'images'));
for (const d of ['cmaps', 'standard_fonts', 'wasm', 'iccs']) add(`/vendor/pdfjs/${d}`, nm('pdfjs-dist', d));
add('/vendor/marked.esm.js', nm('marked', 'lib', 'marked.esm.js'));
add('/vendor/purify.es.mjs', nm('dompurify', 'dist', 'purify.es.mjs'));
add('/vendor/katex/katex.mjs', nm('katex', 'dist', 'katex.mjs'));
add('/vendor/katex/katex.min.css', nm('katex', 'dist', 'katex.min.css'));
// woff2 only: every browser that runs the reader picks it first, so the woff/ttf fallbacks would be dead weight.
for (const f of fs.readdirSync(nm('katex', 'dist', 'fonts'))) if (f.endsWith('.woff2')) add(`/vendor/katex/fonts/${f}`, nm('katex', 'dist', 'fonts', f));

fs.writeFileSync(path.join(ROOT, 'src', 'assets.gen.mjs'),
  `// Generated by scripts/build.mjs. Do not edit.\nexport default ${JSON.stringify(assets)};\n`);
const mb = Object.values(assets).reduce((n, b) => n + b.length * 0.75, 0) / 1e6;
console.log(`assets: ${Object.keys(assets).length} files, ${mb.toFixed(1)} MB`);

if (process.argv.includes('--compile')) {
  const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
  const only = process.argv.find((a) => a.startsWith('--target='))?.slice(9);
  const targets = only ? [only] : ['linux-x64', 'linux-arm64', 'darwin-x64', 'darwin-arm64', 'windows-x64'];
  fs.mkdirSync(path.join(ROOT, 'dist'), { recursive: true });
  for (const t of targets) {
    const out = path.join(ROOT, 'dist', `sidenote-${t}${t.startsWith('windows') ? '.exe' : ''}`);
    execFileSync('bun', ['build', '--compile', '--minify', `--target=bun-${t}`,
      `--define`, `process.env.SIDENOTE_VERSION="${version}"`,
      path.join(ROOT, 'bin', 'sidenote.mjs'), '--outfile', out], { stdio: 'inherit' });
  }
}
